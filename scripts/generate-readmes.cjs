function expectedReadmes(repository = root) {
    const files = new Map();
    const rows = [];
    for (const [code, asset] of Object.entries(languageAssets)) {
        const locale = path.basename(asset, ".js");
        const dictionary = readDictionary(path.join(repository, asset));
        const file = `docs/readme/${locale}/README.md`;
        files.set(
            file,
            renderQuickStart(
                dictionary,
                ["_ara", "_heb", "_per", "_pus", "_snd", "_urd"].includes(code)
            )
        );
        rows.push(
            `- [${inline(dictionary.lang)}](${locale}/README.md) — \`${code}\``
        );
    }
    files.set(
        "docs/readme/README.md",
        `<!-- Generated by scripts/generate-readmes.cjs. -->
# Localized quick starts · Краткие инструкции

[English manual](../../README.md) · [Русское руководство](../../README.ru.md) · [Wiki](../wiki/Home.md)

The ${rows.length} guides below use the actual translated UI captions shipped with
the player. They cover opening the demo, selecting the interface language,
loading an M3U playlist and finding settings. Commands, product names and
explicitly marked links to English/Russian manuals are shared. These are
**localized quick starts, not ${rows.length} full translated engineering manuals**.
The complete practical guides and new feature documentation are maintained in
English and Russian. Automated catalog parity does not replace native-speaker
review; please report unclear or incorrect translations.

Ниже — ${rows.length} краткие инструкции с реальными переведёнными подписями интерфейса:
демо, выбор языка, загрузка M3U и поиск настроек. Команды, названия продуктов и
явно обозначенные ссылки на EN/RU-руководства общие. Это **локализованный краткий
запуск, а не ${rows.length} полных переводов инженерных руководств**. Полные практические
руководства и документация новых функций поддерживаются на английском и русском.
Проверка совпадения каталогов не заменяет вычитку носителем языка.

## Languages · Языки

${rows.join("\n")}

## Maintenance · Поддержка

Generated from \`src/localization/assets.ts\` and \`locales/*.js\`. Do not edit
these quick starts by hand. Update the translation catalog or shared template,
regenerate, and run the documentation check:

Файлы генерируются из \`src/localization/assets.ts\` и \`locales/*.js\`. Исправляйте
каталог переводов или общий шаблон, затем пересоздавайте инструкции и проверяйте:

\`\`\`sh
npm run docs:generate
npm run check:docs
\`\`\`

The check requires one guide per shipped locale, exact generated content and
existing relative link destinations in these guides, root READMEs and wiki
navigation. It does not fetch external sites or validate every heading anchor.
A stale guide or a removed/renamed language causes a failure rather than being
silently kept as another supported locale.
`
    );
    return files;
}

function checkGenerated(repository = root) {
    const expected = expectedReadmes(repository);
    const errors = [];
    for (const [file, content] of expected) {
        const absolute = path.join(repository, file);
        if (
            !fs.existsSync(absolute) ||
            fs.readFileSync(absolute, "utf8") !== content
        )
            errors.push(`Stale or missing generated guide: ${file}`);
    }
    const directory = path.join(repository, "docs/readme");
    if (fs.existsSync(directory)) {
        for (const entry of fs.readdirSync(directory, {
            withFileTypes: true,
        })) {
            const file = `docs/readme/${entry.name}/README.md`;
            if (entry.isDirectory() && !expected.has(file))
                errors.push(`Unknown locale guide directory: ${entry.name}`);
        }
    }
    return errors;
}

if (require.main === module) {
    if (process.argv.includes("--check")) {
        const errors = checkGenerated();
        if (errors.length) {
            console.error(errors.join("\n"));
            process.exitCode = 1;
        } else
            console.log(
                `PASS ${Object.keys(languageAssets).length} generated locale guides`
            );
    } else {
        for (const [file, content] of expectedReadmes()) {
            const absolute = path.join(root, file);
            fs.mkdirSync(path.dirname(absolute), { recursive: true });
            fs.writeFileSync(absolute, content);
        }
        console.log(
            `Generated ${Object.keys(languageAssets).length} locale guides and index`
        );
    }
}
module.exports = { checkGenerated, expectedReadmes, renderQuickStart };
